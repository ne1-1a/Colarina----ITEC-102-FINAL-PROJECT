# Example 1 (Easy): print() basics
print("Hello, world!")
print(42)
print(3.14)

# Many items: print puts a space between them
print("Python", "is", "fun")

# sep= changes what goes BETWEEN items
print("Python", "is", "fun", sep="-")
print("2026", "11", "19", sep="/")

# end= changes what goes at the END (default is a new line)
print("Loading", end="...")
print("done!")

print()                      # an empty line
print("Total:", 10 + 5)      # print can do math too
print("10 + 5 =", 10 + 5)
