# Example 1 (Easy): The 7 arithmetic operators
a = 17
b = 5

print("a + b  =", a + b)      # addition
print("a - b  =", a - b)      # subtraction
print("a * b  =", a * b)      # multiplication
print("a / b  =", a / b)      # division (always a float)
print("a // b =", a // b)     # floor division (drops the decimals)
print("a % b  =", a % b)      # modulo (the remainder)
print("a ** b =", a ** b)     # power
